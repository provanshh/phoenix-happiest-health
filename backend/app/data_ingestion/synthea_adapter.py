"""Ingestion adapter for Synthea Synthetic Electronic Health Records."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any
import pandas as pd

from .base_adapter import BaseDatasetAdapter
from .dataset_registry import get_dataset_info
from .provenance import ProvenanceMetadata, ProvenanceType, make_provenance


DEFAULT_FIXTURES_DIR = Path(__file__).resolve().parents[1] / "data" / "research_fixtures" / "synthea"


class SyntheaDatasetAdapter(BaseDatasetAdapter):
    """Adapter for Synthea synthetic patient clinical records."""

    def __init__(self, data_dir: Path | str | None = None) -> None:
        super().__init__(dataset_id="synthea", data_dir=data_dir or DEFAULT_FIXTURES_DIR)
        self.metadata = get_dataset_info("synthea") or {}

    def list_available_records(self) -> list[str]:
        if not self.data_dir or not self.data_dir.exists():
            return []
        records = []
        for file in self.data_dir.glob("*.json"):
            records.append(file.stem)
        for file in self.data_dir.glob("*.csv"):
            records.append(file.stem)
        return sorted(list(set(records)))

    def load_record(self, record_id: str) -> dict[str, Any]:
        """Load a Synthea patient record from JSON or CSV fixture."""
        if not self.data_dir:
            raise FileNotFoundError("Synthea data directory is not configured.")

        json_file = self.data_dir / f"{record_id}.json"
        if json_file.exists():
            data = json.loads(json_file.read_text(encoding="utf-8"))
            provenance = self.get_provenance(record_id)
            return {
                "record_id": record_id,
                "is_synthetic": True,
                "provenance": provenance.to_dict(),
                "patient": data.get("vitals") or data.get("patient") or data,
                "conditions": data.get("conditions", []),
                "observations": data.get("observations", {}),
                "synthetic_notice": "SYNTHETIC RESEARCH RECORD — Generated by Synthea model; not a real human patient.",
            }

        csv_file = self.data_dir / f"{record_id}.csv"
        if csv_file.exists():
            df = pd.read_csv(csv_file)
            row = df.iloc[0].to_dict()
            provenance = self.get_provenance(record_id)
            return {
                "record_id": record_id,
                "is_synthetic": True,
                "provenance": provenance.to_dict(),
                "patient": row,
                "synthetic_notice": "SYNTHETIC RESEARCH RECORD — Generated by Synthea model; not a real human patient.",
            }

        raise FileNotFoundError(f"Synthea record {record_id} not found in {self.data_dir}")

    def get_provenance(self, record_id: str) -> ProvenanceMetadata:
        return make_provenance(
            provenance_type=ProvenanceType.SYNTHETIC_EHR,
            source_dataset="Synthea Synthetic Electronic Health Records v3.0.0",
            record_id=record_id,
            license_str=self.metadata.get("license", "Apache License 2.0"),
            dataset_url=self.metadata.get("source_url"),
            is_synthetic=True,
            is_clinical_evidence=False,
            units_map={
                "systolic_bp": "mmHg",
                "diastolic_bp": "mmHg",
                "heart_rate": "bpm",
                "spo2": "%",
                "height": "cm",
                "weight": "kg",
            },
            limitations=self.metadata.get("known_limitations", []),
            attribution=self.metadata.get("attribution", ""),
        )
